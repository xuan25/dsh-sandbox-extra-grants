/**
 * dsh-sandbox-extra-grants
 *
 * A composition decorator around the built-in local sandbox provider: after the
 * backing provider wraps an argv for a policy, it splices extra path grants
 * (files, device nodes, directories) into the runner's own dialect, so a
 * confined command can touch paths the built-in profile deliberately excludes
 * (e.g. `/dev/nvidia0` for GPU access, `/dev/dri` for GPU rendering).
 *
 * Grants are scoped per sandbox policy MODE: the config maps each confined
 * policy mode (`read-only`, `workspace-write` - the framework's closed mode
 * set) to a list of grant entries. Each entry is a string in the docker
 * `-v` path-suffix style: `/path` (default mode `rw`), `/path:ro` (read-only),
 * or `/path:rw` (read-write). Any other suffix is a configuration error; in
 * particular `w` (write-only) is rejected, because no runner dialect can
 * express it.
 *
 * Grant dialects are recognized from the confined argv SHAPE (argv[0]), not
 * from who produced it, so the decorator binds to the abstract provider
 * contract only:
 *   - bwrap, or a configured operator runner (`argv[0] === runnerCommand[0]`):
 *     device nodes as `--dev-bind <path> <path>` pairs (read-write only: bwrap
 *     has no read-only device bind, so a read-only device grant fails the
 *     command), files and directories as `--ro-bind` / `--bind` pairs
 *   - the landlock-run launcher: `--ro` / `--rw` flags, generated by the
 *     framework's own `grantArgs` (read-only grants first, caller order kept
 *     within each mode; the launcher consumes the grants as a set)
 *   - anything else: fail closed with `SandboxUnsupportedPolicyError`
 *
 * The insertion point is the exact position of the single `--` the backing
 * provider appends before the wrapped command, computed from the original argv
 * length (the command may legally carry its own `--`), with a fail-closed
 * shape check on top. The shape check runs on EVERY confine call - even for a
 * policy mode that carries no grants - so a backing that failed to wrap can
 * never let a command run unconfined.
 *
 * The backing provider is built in an isolated cordis realm: a service
 * registers itself with the context it is constructed on, so building the
 * backing on the plugin context would register a second `sandbox` and make the
 * composition fail to start. The isolated realm keeps that registration
 * invisible to the root context; this provider is the sole root-side
 * `sandbox` service.
 *
 * Config lifting: `static Config` groups the backing provider's own schema
 * under a single optional `backing` field, intersected with this plugin's own
 * `grants` field, so one composition entry carries both and the two config
 * surfaces stay separated: `grants` is plugin-owned, `backing` is a
 * pass-through (an omitted `backing` means every backing knob at the
 * framework default). Referencing the backing schema directly keeps the lifted
 * set in step when the backing schema grows; the backing knobs are validated
 * by the backing schema and consumed by the backing constructor at service
 * start.
 *
 * Hot reload: grant edits apply to NEW sessions only; pre-existing sessions
 * pin the provider instance they were composed with until process restart.
 */

import type { Context } from '@deepseek-ai/cordis'
import z from '@deepseek-ai/schemastery'
import { stat } from 'node:fs/promises'
import {
  SandboxProvider,
  SandboxUnsupportedPolicyError,
  type ConfinedArgv,
  type ConfinedSandboxMode,
  type SandboxPolicy,
} from '@deepseek-ai/dsh-sandbox'
import { LocalSandboxProvider, type Config as LocalConfig } from '@deepseek-ai/dsh-sandbox-local'
import { grantArgs as landlockGrantArgs, launcherPath } from '@deepseek-ai/node-addon-system/landlock-run'

/** The per-grant access mode, in the docker `-v` spelling. `rw` is the default for a bare path. */
export type GrantMode = 'ro' | 'rw'

/** A grant entry after suffix parsing: the absolute path and its access mode. */
export interface ParsedGrant {
  /** The grant path (always absolute). */
  readonly path: string
  /** The grant access mode; `rw` for a bare (suffix-less) entry. */
  readonly mode: GrantMode
}

/** A grant whose path class has been resolved (device node, or file/directory). */
export interface ClassifiedGrant {
  /** The grant path. */
  readonly path: string
  /** The grant access mode. */
  readonly mode: GrantMode
  /** True when the path is a character device node. */
  readonly device: boolean
}

/** Runner facts needed to express the grants in the runner's own dialect. */
export interface GrantEnv {
  /** Head of the configured operator runner command; its argv takes bwrap-dialect pairs. Absent when no runner is configured. */
  readonly runnerCommandHead?: string
  /** The landlock-run launcher path; its argv takes `--ro`/`--rw` flags. */
  readonly launcher: string
  /** The host process platform; grants are supported on `linux` only. */
  readonly platform: string
}

/**
 * The decorated provider's config: the backing provider's config, grouped
 * under one field, plus the plugin-owned per-mode grant map.
 */
export interface ExtraGrantsConfig {
  /**
   * The backing provider's own config (runner override, failure signatures,
   * probe timeout) passed through untouched. Omitted = every backing knob at
   * the framework default.
   */
  readonly backing?: LocalConfig
  /**
   * Extra path grants per policy mode, keyed by the framework's confined
   * policy mode. Each entry is `<absolute path>`, `<path>:ro`, or
   * `<path>:rw`; a bare path is read-write. Omitted or empty = inert.
   */
  readonly grants?: Partial<Record<ConfinedSandboxMode, readonly string[]>>
}

/**
 * Parse one grant entry (docker `-v` path-suffix style) into path + mode.
 * @param entry - the raw config string.
 * @returns the parsed grant.
 * @throws {Error} when the entry is empty, carries a trailing colon, names a
 * relative path, or uses a suffix other than `ro` / `rw` (`w` gets a
 * dedicated message: no runner dialect can express write-only).
 */
export function parseGrantEntry(entry: string): ParsedGrant {
  if (typeof entry !== 'string' || entry.length === 0) {
    throw new Error(`sandbox-extra-grants: grant entry must be a non-empty string, got ${JSON.stringify(entry)}`)
  }
  const colon = entry.lastIndexOf(':')
  const path = colon === -1 ? entry : entry.slice(0, colon)
  const suffix = colon === -1 ? '' : entry.slice(colon + 1)
  let mode: GrantMode
  if (suffix === '' && colon === -1) mode = 'rw'
  else if (suffix === 'ro') mode = 'ro'
  else if (suffix === 'rw') mode = 'rw'
  else if (suffix === '') throw new Error(`sandbox-extra-grants: grant entry ${JSON.stringify(entry)} has a trailing ':' with no mode suffix (drop it, or use ':ro' / ':rw')`)
  else if (suffix === 'w') throw new Error(`sandbox-extra-grants: grant entry ${JSON.stringify(entry)} uses mode 'w', which no runner dialect can express (write-only access does not exist in bwrap or landlock); use 'rw' instead`)
  else throw new Error(`sandbox-extra-grants: grant entry ${JSON.stringify(entry)} has unknown access-mode suffix '${suffix}' (expected ':ro' or ':rw')`)
  if (path.length === 0) {
    throw new Error(`sandbox-extra-grants: grant entry ${JSON.stringify(entry)} names an empty path`)
  }
  if (!path.startsWith('/')) {
    throw new Error(`sandbox-extra-grants: grant entry ${JSON.stringify(entry)} names a relative path; grant paths must be absolute`)
  }
  return { path, mode }
}

/**
 * Parse and normalize a grant list: each entry is parsed, then duplicate
 * paths collapse to one grant keeping the more permissive mode
 * (`rw` over `ro`), first-seen order preserved.
 * @param entries - the raw config strings for one policy mode.
 * @returns the deduplicated parsed grants.
 * @throws {Error} on any invalid entry (see {@link parseGrantEntry}).
 */
export function resolveGrants(entries: readonly string[]): ParsedGrant[] {
  const byPath = new Map<string, ParsedGrant>()
  for (const entry of entries) {
    const parsed = parseGrantEntry(entry)
    const existing = byPath.get(parsed.path)
    if (!existing) {
      byPath.set(parsed.path, parsed)
    }
    else if (parsed.mode === 'rw' && existing.mode === 'ro') {
      byPath.set(parsed.path, parsed)
    }
  }
  return [...byPath.values()]
}

/**
 * Pure argv transform: splice the grants at the position of the `--` the
 * backing provider appended before the wrapped command. Exported for tests;
 * production traffic goes through {@link ExtraGrantsSandboxProvider}.
 * With no grants the transform is a no-op (fresh copy) and never consults the
 * runner dialect or the platform.
 * @param confined - the backing provider's confined argv.
 * @param originalArgv - the argv as it was passed to the backing provider.
 * @param grants - the classified extra path grants.
 * @param env - the runner facts that select the grant dialect.
 * @returns a new confined argv; the input is never mutated.
 * @throws {SandboxUnsupportedPolicyError} on non-Linux platforms (with grants), an unknown runner dialect (with grants), or a confined argv whose shape does not match.
 */
export function applyExtraGrants(
  confined: ConfinedArgv,
  originalArgv: readonly string[],
  grants: readonly ClassifiedGrant[],
  env: GrantEnv,
): ConfinedArgv {
  const insertion = confined.argv.length - originalArgv.length - 1
  if (insertion <= 0 || confined.argv[insertion] !== '--') {
    throw new SandboxUnsupportedPolicyError('sandbox-extra-grants: the confined argv does not match the expected shape')
  }
  if (grants.length === 0) {
    return { ...confined, argv: [...confined.argv] }
  }
  if (env.platform !== 'linux') {
    throw new SandboxUnsupportedPolicyError('sandbox-extra-grants: grants are supported on linux only')
  }
  let added: string[]
  const runner = confined.argv[0]
  if (runner === 'bwrap' || (env.runnerCommandHead !== undefined && runner === env.runnerCommandHead)) {
    added = grants.flatMap((grant) => {
      if (grant.device) {
        if (grant.mode === 'ro') {
          throw new SandboxUnsupportedPolicyError(`sandbox-extra-grants: bwrap has no read-only device bind; grant ${JSON.stringify(grant.path)} cannot be expressed read-only (use 'rw')`)
        }
        return ['--dev-bind', grant.path, grant.path]
      }
      return grant.mode === 'ro' ? ['--ro-bind', grant.path, grant.path] : ['--bind', grant.path, grant.path]
    })
  }
  else if (runner === env.launcher) {
    added = landlockGrantArgs({
      readOnly: grants.filter((grant) => grant.mode === 'ro').map((grant) => grant.path),
      readWrite: grants.filter((grant) => grant.mode === 'rw').map((grant) => grant.path),
    })
  }
  else {
    throw new SandboxUnsupportedPolicyError(
      `sandbox-extra-grants: runner "${runner}" has no known grant dialect for the configured grants`,
    )
  }
  const argv = [...confined.argv]
  argv.splice(insertion, 0, ...added)
  return { ...confined, argv }
}

/** The realm label of the isolated backing provider; a service registered in that realm is invisible to the root context. */
const BACKING_REALM: unique symbol = Symbol('dsh-sandbox-extra-grants-backing')

/** The custom schema type of the per-mode grant map (a resolver the plugin registers with the schema library). */
const MODE_GRANTS_TYPE = 'dsh-sandbox-extra-grants:mode-grants'

/**
 * Register the resolver for the per-mode grant map. The built-in object schema
 * silently drops unknown keys in the nested (strict) context a config
 * intersection uses, so the closed mode key set is enforced here instead:
 * every key must be one of the framework's confined policy modes, and each
 * value must be a list of grant entry strings.
 */
z.extend(MODE_GRANTS_TYPE, (data, schema, options) => {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) {
    throw new z.ValidationError(`sandbox-extra-grants: grants must be an object keyed by policy mode, got ${JSON.stringify(data)}`, options)
  }
  const inner = schema.inner
  if (!inner) {
    throw new z.ValidationError('sandbox-extra-grants: the grants schema is missing its entry schema', options)
  }
  const result: Record<string, unknown> = {}
  for (const key of Object.keys(data)) {
    if (key !== 'read-only' && key !== 'workspace-write') {
      throw new z.ValidationError(`sandbox-extra-grants: unknown policy mode '${key}' in grants (expected 'read-only' or 'workspace-write')`, options)
    }
    result[key] = z.resolve((data as Record<string, unknown>)[key], inner, { ...options, path: [...(options.path ?? []), key] })[0]
  }
  return [result]
})

/** The per-mode grant map schema: an object keyed by the closed policy-mode set, each value a list of grant entry strings; the field is optional. */
const modeGrantsSchema = z<Partial<Record<ConfinedSandboxMode, readonly string[]>>>({
  type: MODE_GRANTS_TYPE,
  inner: z.array(z.string()),
})

/** Resolve the path class of one grant: a character device node, or a file/directory (missing paths are treated as files). */
async function classifyGrant(grant: ParsedGrant): Promise<ClassifiedGrant> {
  try {
    const stats = await stat(grant.path)
    return { path: grant.path, mode: grant.mode, device: (stats.mode & 0o170000) === 0o020000 }
  }
  catch {
    return { path: grant.path, mode: grant.mode, device: false }
  }
}

/**
 * A sandbox provider that decorates {@link LocalSandboxProvider}: identical
 * confinement behavior, plus per-policy-mode path grants (read-only and/or
 * read-write, per grant) spliced into the confined argv in the runner's own
 * dialect.
 */
export class ExtraGrantsSandboxProvider extends SandboxProvider {
  /** The plugin name, mirroring the package name (the loader's display name). */
  static name = 'dsh-sandbox-extra-grants'

  /** Lifted config: the backing provider's schema grouped under the optional `backing` field, intersected with the optional per-mode grants field (the grants key set is enforced by the plugin's resolver). */
  static Config = z.intersect([
    z.object({ backing: LocalSandboxProvider.Config }),
    z.object({ grants: modeGrantsSchema }),
  ])

  /** The decorated backing provider, built in an isolated realm (see module docs). */
  private readonly impl: LocalSandboxProvider
  /** The parsed, deduplicated grants per policy mode. */
  private readonly grantsByMode: Partial<Record<ConfinedSandboxMode, ParsedGrant[]>>
  private readonly runnerCommandHead: string | undefined

  constructor(ctx: Context, config: ExtraGrantsConfig) {
    super(ctx)
    this.grantsByMode = {}
    if (config.grants !== undefined) {
      for (const mode of Object.keys(config.grants) as ConfinedSandboxMode[]) {
        this.grantsByMode[mode] = resolveGrants(config.grants[mode] ?? [])
      }
    }
    // The schema passes unknown top-level keys through untouched, so a
    // top-level backing knob would vanish silently; reject it loudly and point
    // the operator at `backing.<field>`.
    for (const field of ['runnerCommand', 'runnerFailureSignatures', 'probeTimeoutMs']) {
      if (Object.prototype.hasOwnProperty.call(config, field)) {
        throw new Error(`sandbox-extra-grants: the backing knob '${field}' must be set under the 'backing' field, not at the top level; set backing.${field} instead`)
      }
    }
    // Materialize the backing config: an omitted `backing` resolves to the
    // framework defaults; a present one is already schema-resolved, and
    // re-resolving it is idempotent.
    const backing = LocalSandboxProvider.Config(config.backing ?? {})
    const runner = backing.runnerCommand ?? []
    this.runnerCommandHead = runner.length > 0 ? runner[0] : undefined
    this.impl = new LocalSandboxProvider(ctx.isolate('sandbox', BACKING_REALM), backing)
  }

  async confine(
    argv: readonly string[],
    policy: SandboxPolicy,
    signal?: AbortSignal,
  ): Promise<ConfinedArgv> {
    const confined = await this.impl.confine(argv, policy, signal)
    // Fail-closed shape check on every call, even when this policy mode carries
    // no grants: a backing that failed to wrap its marker must not let the
    // command run unconfined.
    const insertion = confined.argv.length - argv.length - 1
    if (insertion <= 0 || confined.argv[insertion] !== '--') {
      throw new SandboxUnsupportedPolicyError('sandbox-extra-grants: the confined argv does not match the expected shape')
    }
    const specs = this.grantsByMode[policy.mode] ?? []
    if (specs.length === 0) return confined
    const grants = await Promise.all(specs.map(classifyGrant))
    return applyExtraGrants(confined, argv, grants, {
      runnerCommandHead: this.runnerCommandHead,
      launcher: launcherPath(),
      platform: process.platform,
    })
  }
}

/** Plugin entry: the loader starts the class (default export), which registers itself as the profile's `sandbox` service. */
export default ExtraGrantsSandboxProvider
